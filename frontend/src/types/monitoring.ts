export type MonitoringSession = {
  id: string;
  stationId: string;
  stationName: string;
  connectorId: string;
  connectorLabel: string;
  connectorType: string;
  status: "starting" | "active" | "stopping" | "completed" | "failed";
  requestedAt: string;
  startedAt: string | null;
  endedAt: string | null;
  allocatedPowerW: number;
  currentPowerW: number | null;
  lastPowerW: number | null;
  knownEnergyWh: number | null;
  lastMeasuredAt: string | null;
  ageSeconds: number | null;
  telemetry: "fresh" | "stale" | "missing" | "offline";
  gap: boolean;
  telemetryGap: boolean;
  source: "simulator";
  finalCostKopecks: number | null;
};
export type PowerCoverage = {
  measuredPowerW: number | null;
  measuredSubsetPowerW: number | null;
  allocatedPowerW: number;
  measuredSessions: number;
  expectedSessions: number;
  complete: boolean;
  telemetryCounts: Record<string, number>;
};
export type MonitoringStation = PowerCoverage & {
  id: string;
  name: string;
  status: string;
  archivedAt: string | null;
  localLimitKw: number;
  physicalMaxKw: number;
  lastMeasuredAt: string | null;
  sessionCounts: Record<MonitoringSession["status"], number>;
};
export type MonitoringSnapshot = PowerCoverage & {
  asOf: string;
  source: "simulator";
  scope: string;
  gridBudgetKw: null;
  gridReserveKw: null;
  sessionCounts: Record<MonitoringSession["status"], number>;
  knownEnergyWh: number | null;
  completedTestCostKopecks: number;
  stations: MonitoringStation[];
  sessions: MonitoringSession[];
};
export type PowerHistory = {
  stationId: string;
  stationName: string;
  intervalStart: string;
  intervalEnd: string;
  measuredEnergyWh: number | null;
  averagePowerW: number | null;
  measuredSubsetAverageW: number | null;
  activeSessions: number;
  localLimitKw: number;
  source: "simulator";
  quality: "complete" | "partial" | "missing";
  observedMs: number;
  coveredSessionMs: number;
  expectedSessionMs: number;
  sampleCount: number;
  gapCount: number;
  boundaryCount: number;
  unattributedEnergyWh: number;
  firstSampleAt: string | null;
  lastSampleAt: string | null;
  builtAt: string;
  rule: string;
};
export type TechnicalEvent = {
  id: string;
  stationId: string;
  sessionId: string;
  at: string;
  kind: string;
  status: string;
};
export type MonitoringPage<T> = { items: T[]; nextCursor: string | null };
